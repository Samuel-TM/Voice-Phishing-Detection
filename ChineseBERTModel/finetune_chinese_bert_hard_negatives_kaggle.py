# Fine-tune Chinese-BERT with finance semantic contrast data on Kaggle.
#
# Purpose:
#   Continue from the existing Chinese-BERT text-risk checkpoint and add a
#   finance semantic contrast set: realistic oral normal-finance hard negatives
#   plus same-vocabulary fraud positives. This avoids training only on explicit
#   "do not give verification codes" safety-advice sentences.
#
# Baseline compatibility:
#   - Reuses the TeleAntiFraud loading, dedup, label convention, and
#     ChineseBERTClassifier architecture from baseline-of-chinese-bert.py.
#   - Reuses the gradient training/checkpoint style from
#     ChineseBERTModel/train_chinese_bert_kaggle.py.
#
# Expected Kaggle inputs:
#   1. TeleAntiFraud-28k dataset directory.
#   2. finance_semantic_contrast_train_val.jsonl generated by
#      evaluation/generate_benign_finance_hard_negatives.py.
#   3. Optional but recommended: current baseline best_model.pt/train.pt.
#   4. Optional for no-internet Kaggle runs: a local bert-base-chinese folder.
#
# Label convention:
#   text_label=1 means phishing/fraud semantics.
#   text_label=0 means benign text semantics, even if it contains finance words.

